"""LLM adapter service supporting OpenAI-compatible, Anthropic, and Gemini APIs."""
from __future__ import annotations
import logging, os, re
from typing import Any
import httpx

logger = logging.getLogger(__name__)
_REDACT_PATTERNS = [re.compile(r"(sk-[A-Za-z0-9]{20,})", re.I), re.compile(r"(Bearer\s+[A-Za-z0-9\-_\.]{20,})", re.I), re.compile(r"(key=[A-Za-z0-9\-_]{20,})", re.I)]

def _redact_error(msg: str) -> str:
    for pat in _REDACT_PATTERNS: msg = pat.sub("[REDACTED]", msg)
    return msg

class LLMAdapterError(Exception): pass

class LLMAdapters:
    def __init__(self):
        self.provider = os.getenv("LLM_PROVIDER", "openai-compatible")
        self.api_key = os.getenv("LLM_API_KEY", "")
        self.model = os.getenv("LLM_MODEL", "gpt-4o-mini")
        self.base_url = os.getenv("LLM_BASE_URL", "")
        self.timeout = float(os.getenv("LLM_TIMEOUT", "20.0"))

    def is_configured(self) -> bool: return bool(self.api_key and self.api_key.strip())
    def advisory_label(self) -> str: return "⚠️ AI Advisory (opt-in): This analysis is generated by an LLM and may contain inaccuracies."

    def analyze_deck(self, deck_title: str, slide_summaries: list[str], task: str = "review") -> dict[str, Any]:
        if not self.is_configured(): return self._offline_advisory(deck_title, slide_summaries, task)
        prompt = self._build_prompt(deck_title, slide_summaries, task)
        try: return {"advisory": self._call_provider(prompt), "provider": self.provider, "model": self.model, "label": self.advisory_label(), "offline": False}
        except LLMAdapterError as exc: return {"advisory": None, "provider": self.provider, "model": self.model, "label": self.advisory_label(), "error": str(exc), "offline": False}
        except Exception as exc: return {"advisory": None, "provider": self.provider, "model": self.model, "label": self.advisory_label(), "error": f"Provider error: {_redact_error(str(exc))}", "offline": False}

    def _offline_advisory(self, title: str, summaries: list[str], task: str) -> dict[str, Any]:
        st = "; ".join(summaries[:5]) if summaries else "no slides"
        return {"advisory": f"[Offline summary] Deck '{title}' covers: {st}. Configure LLM_API_KEY for AI-powered analysis.", "provider": "offline", "model": "none", "label": "[Offline deterministic summary — no LLM configured]", "offline": True}

    def _build_prompt(self, title: str, summaries: list[str], task: str) -> str:
        s_block = "\n".join(f"- {s}" for s in summaries[:15])
        return f"Deck title: {title}\n\nSlide summaries:\n{s_block}\n\nTask: {task}\nProvide concise advisory review. Max 300 words."

    def _call_provider(self, prompt: str) -> str:
        p = self.provider.lower()
        if p in ("openai-compatible", "openai", "openrouter", "litellm", "ollama"): return self._call_openai_compatible(prompt)
        if p == "anthropic": return self._call_anthropic(prompt)
        if p == "gemini": return self._call_gemini(prompt)
        raise LLMAdapterError(f"Unknown provider: {p}. Use openai-compatible, anthropic, or gemini.")

    def _call_openai_compatible(self, prompt: str) -> str:
        url = f"{(self.base_url or 'https://api.openai.com/v1').rstrip('/')}/chat/completions"
        with httpx.Client(timeout=self.timeout) as client:
            resp = client.post(url, json={"model": self.model, "messages": [{"role": "user", "content": prompt}], "max_tokens": 400, "temperature": 0.3}, headers={"Authorization": f"Bearer {self.api_key}", "Content-Type": "application/json"})
            resp.raise_for_status(); return resp.json()["choices"][0]["message"]["content"].strip()

    def _call_anthropic(self, prompt: str) -> str:
        with httpx.Client(timeout=self.timeout) as client:
            resp = client.post("https://api.anthropic.com/v1/messages", json={"model": self.model or "claude-3-haiku-20240307", "max_tokens": 400, "messages": [{"role": "user", "content": prompt}]}, headers={"x-api-key": self.api_key, "anthropic-version": "2023-06-01", "Content-Type": "application/json"})
            resp.raise_for_status(); return resp.json()["content"][0]["text"].strip()

    def _call_gemini(self, prompt: str) -> str:
        model = self.model or "gemini-1.5-flash"
        with httpx.Client(timeout=self.timeout) as client:
            resp = client.post(f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent", json={"contents": [{"parts": [{"text": prompt}]}], "generationConfig": {"maxOutputTokens": 400, "temperature": 0.3}}, headers={"Content-Type": "application/json"}, params={"key": self.api_key})
            resp.raise_for_status(); return resp.json()["candidates"][0]["content"]["parts"][0]["text"].strip()